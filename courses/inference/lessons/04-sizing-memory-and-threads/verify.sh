source "$KDRILL_HOME/courses/inference/lib.sh"
C='{.spec.template.spec.containers[0]'
settle llm 60 || true
h="$(current_hash llm)"; sel="app=llm,pod-template-hash=$h"
args="$(jp deploy/llm "$C.args[*]}")"
mem_limit="$(jp deploy/llm "$C.resources.limits.memory}")"
mem_req="$(jp deploy/llm "$C.resources.requests.memory}")"
cpu_limit="$(jp deploy/llm "$C.resources.limits.cpu}")"
mib() { case "$1" in *Gi) echo $(( ${1%Gi} * 1024 )) ;; *Mi) echo "${1%Mi}" ;; *Ki) echo $(( ${1%Ki} / 1024 )) ;; *) echo $(( $1 / 1048576 )) ;; esac; }
check_eq "The server is ready (current ReplicaSet)" 1 "$(ready_pods "$sel")"
why "kubectl describe pod -l app=llm shows 'Last State: Terminated  Reason: OOMKilled'."
check_eq "... and was not OOMKilled or restarted" 0 "$(restarts "$sel")"
check "The memory limit is at most 450Mi (limit: ${mem_limit:-none})" bash -c '[[ -n "$1" ]] && (( $2 <= 450 ))' _ "$mem_limit" "$(mib "${mem_limit:-0}")"
why "Do not just raise the limit: the node has no room. Look at what the memory is spent on (the KV cache grows with the context length)."
check_eq "Memory request equals the limit (guaranteed memory: no overcommit, no surprise eviction)" "$mem_limit" "$mem_req"
rss="$(kubectl exec deploy/llm -- sh -c "grep VmHWM /proc/1/status" 2>/dev/null | awk '{print int($2/1024)}')"
lim_mib="$(mib "${mem_limit:-0}")"
check "Headroom: the limit is at least 15% above the server's peak memory (peak ${rss:-?} MiB, limit $lim_mib MiB)" bash -c '[[ -n "$1" ]] && (( $2 * 100 >= $1 * 115 ))' _ "$rss" "$lim_mib"
why "kubectl exec deploy/llm -- grep VmHWM /proc/1/status gives the peak resident memory in kB."
slots="$(kx curl -s --max-time 10 http://llm/slots)"
n="$(printf '%s' "$slots" | grep -o '"id":[0-9]*' | wc -l | tr -d ' ')"
nctx="$(printf '%s' "$slots" | grep -o '"n_ctx":[0-9]*' | head -n 1 | cut -d: -f2)"
check_ge "The server keeps at least 4 parallel slots (got ${n:-0})" 4 "${n:-0}"
check_ge "... each with a context of at least 1024 tokens (got ${nctx:-0})" 1024 "${nctx:-0}"
why "Per-slot context = -c / --parallel. Memory for the KV cache is about 23 KB per token of total -c."
t="$(printf '%s ' $args | sed -n 's/.* -t \([0-9]*\) .*/\1/p;s/.*--threads \([0-9]*\) .*/\1/p' | head -n 1)"
cores=$(( ( $(cpu_millis "${cpu_limit:-0}") + 999 ) / 1000 ))
check "Threads (-t ${t:-?}) match the CPU limit (${cpu_limit:-none}): between 1 and $cores" bash -c '[[ -n "$1" ]] && (( $1 >= 1 && $1 <= $2 ))' _ "$t" "$cores"
why "More threads than CPU limit means the kernel throttles the extra ones (CFS quota): slower, not faster."
out="$(ask_out -n 4 -c 4 -t 8 -p 'Name a color.' http://llm/v1/chat/completions)"
check_eq "4 concurrent completions all answer 200" 4 "$(count_matching '^200 ' "$out")"
